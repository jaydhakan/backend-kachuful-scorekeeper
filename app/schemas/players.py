"""Player registry models (plan §6.3)."""

import uuid
from typing import Literal

from pydantic import Field

from app.schemas.common import CamelModel


class AliasOut(CamelModel):
    """Another name the player is known by."""

    display_name: str = Field(..., description="Reserved like a display name, 1-14 characters")
    first_name: str | None = Field(..., description="Optional, never sent publicly")
    last_name: str | None = Field(..., description="Optional, never sent publicly")


class PlayerOut(CamelModel):
    """The contract's Player."""

    id: uuid.UUID = Field(..., description="Registry id (client-generated)")
    display_name: str = Field(..., description="Unique display name, 1-14 characters")
    email: str | None = Field(
        ..., description="Only for the admin, the creator and the linked user; else null"
    )
    photo_url: str | None = Field(..., description="/api/players/{id}/photo?v={rev}, or null")
    first_name: str | None = Field(..., description="Optional, never sent publicly")
    last_name: str | None = Field(..., description="Optional, never sent publicly")
    emoji: str = Field(..., description="Avatar emoji")
    color: str = Field(..., description="Avatar colour, hex")
    aliases: list[AliasOut] = Field(..., description="Other names, oldest first")
    created_by: uuid.UUID | None = Field(..., description="User id that created the player")
    linked_user_id: uuid.UUID | None = Field(..., description="User id linked to this player")
    merged_into: uuid.UUID | None = Field(..., description="Set when merged into another player")
    created_at: int = Field(..., description="Epoch ms")
    updated_at: int = Field(..., description="Epoch ms; the sync cursor")


class PlayerSummaryOut(PlayerOut):
    """The contract's PlayerSummary: Player plus games, last played and creator name.

    `email` is always null here.
    """

    games: int = Field(..., description="Games with this player (not deleted)")
    last_played_at: int | None = Field(..., description="Epoch ms of the latest done round")
    created_by_name: str = Field(..., description="Display name of the creator's player")


class NewPlayerIn(CamelModel):
    """The contract's NewPlayer."""

    id: uuid.UUID = Field(..., description="Registry id generated by the app")
    display_name: str = Field(..., description="1-14 characters; unique ignoring case and spaces")
    email: str | None = Field(
        default=None,
        max_length=254,
        description="Required by POST /api/players; ignored when accepting an invite",
    )
    first_name: str | None = Field(default=None, max_length=40, description="Optional")
    last_name: str | None = Field(default=None, max_length=40, description="Optional")
    emoji: str = Field(..., min_length=1, max_length=16, description="Avatar emoji")
    color: str = Field(..., min_length=1, max_length=32, description="Avatar colour")


class NewAliasIn(CamelModel):
    """`POST /api/players/{id}/aliases`."""

    display_name: str = Field(..., description="1-14 characters; unique among names and aliases")
    first_name: str | None = Field(default=None, max_length=40, description="Optional")
    last_name: str | None = Field(default=None, max_length=40, description="Optional")


class PlayerRefIn(CamelModel):
    """An existing registry player, by id."""

    id: uuid.UUID = Field(..., description="Registry id")


class PlayerPatchIn(CamelModel):
    """`PATCH /api/players/{id}`: only the fields sent change."""

    display_name: str | None = Field(
        default=None, description="Admin, the creator or the linked user"
    )
    email: str | None = Field(
        default=None, max_length=254, description="Admin, the creator or the linked user"
    )
    first_name: str | None = Field(
        default=None, max_length=40, description="Admin, the creator or the linked user"
    )
    last_name: str | None = Field(
        default=None, max_length=40, description="Admin, the creator or the linked user"
    )
    emoji: str | None = Field(
        default=None,
        min_length=1,
        max_length=16,
        description="Admin, the creator or the linked user",
    )
    color: str | None = Field(
        default=None,
        min_length=1,
        max_length=32,
        description="Admin, the creator or the linked user",
    )


class PlayerCheckOut(CamelModel):
    """`GET /api/players/check`: a match or an email match names the player."""

    status: Literal["match", "email_match", "name_taken", "new"] = Field(
        ...,
        description="match = name (or alias) and email belong to one player; "
        "email_match = the email's player goes by other names",
    )
    player: PlayerSummaryOut | None = Field(
        default=None, description="The player, when status is match or email_match"
    )


class PhotoOut(CamelModel):
    """`PUT /api/players/{id}/photo`."""

    photo_url: str = Field(..., description="/api/players/{id}/photo?v={rev}")
